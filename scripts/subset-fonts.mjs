// Build-time Noto Sans SC subset (runs as `prebuild`).
// Collects every CJK / full-width character used in content/, components/, app/ and splits them in two:
//   first: ASCII + the characters the first screen shows (skip link, nav, intro) -> preloaded
//   rest:  every other character on the site                                   -> loaded on demand
// The page font stack lists both families, so the browser picks each glyph from whichever has it.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import subsetFont from 'subset-font';
import { SITE } from '../content/site.ts';

const ROOT = path.resolve(import.meta.dirname, '..');
const SRC_URL =
  'https://raw.githubusercontent.com/google/fonts/2894aab31764f10f29c421bdfd2340d3b382d384/ofl/notosanssc/NotoSansSC%5Bwght%5D.ttf';
const SRC_SHA256 = 'a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da';
const CACHE = path.join(ROOT, 'node_modules/.cache/fonts/NotoSansSC-wght.ttf');
const OUT_DIR = path.join(ROOT, 'public/fonts');
const WEIGHTS = { min: 400, max: 700 };
const WIDE = /[\u2000-\u206f\u3000-\u303f\u3400-\u9fff\uff00-\uffef]/gu;

async function source() {
  const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');
  if (fs.existsSync(CACHE) && sha(fs.readFileSync(CACHE)) === SRC_SHA256)
    return fs.readFileSync(CACHE);
  const res = await fetch(SRC_URL);
  if (!res.ok) throw new Error(`font download failed: ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (sha(buf) !== SRC_SHA256) throw new Error('font download sha256 mismatch');
  fs.mkdirSync(path.dirname(CACHE), { recursive: true });
  fs.writeFileSync(CACHE, buf);
  return buf;
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    return d.isDirectory() ? walk(p) : /\.(tsx?|mdx?)$/.test(d.name) ? [p] : [];
  });
}

const wide = (s) => new Set(s.match(WIDE) ?? []);
const all = new Set();
for (const f of ['content', 'components', 'app'].flatMap((d) => walk(path.join(ROOT, d))))
  for (const c of wide(fs.readFileSync(f, 'utf8'))) all.add(c);
const firstText = [
  SITE.skipLink,
  SITE.menuOpen,
  SITE.menuClose,
  ...SITE.nav.map((n) => n.label),
  ...Object.values(SITE.intro),
].join('');
const first = [...wide(firstText)].sort();
const rest = [...all].filter((c) => !first.includes(c)).sort();
let ascii = '';
for (let i = 0x20; i < 0x7f; i++) ascii += String.fromCharCode(i);

const font = await source();
fs.mkdirSync(OUT_DIR, { recursive: true });
for (const f of fs.readdirSync(OUT_DIR))
  if (/^noto-sc-/.test(f)) fs.rmSync(path.join(OUT_DIR, f));
const out = {};
for (const [name, text] of [
  ['first', ascii + first.join('')],
  ['rest', rest.join('')],
]) {
  const buf = await subsetFont(font, text, {
    targetFormat: 'woff2',
    variationAxes: { wght: WEIGHTS },
  });
  const file = `noto-sc-${name}.${crypto.createHash('sha256').update(buf).digest('hex').slice(0, 8)}.woff2`;
  fs.writeFileSync(path.join(OUT_DIR, file), buf);
  out[name] = { url: `/fonts/${file}`, chars: [...text].length, bytes: buf.length };
}
const face = (family, url) =>
  `@font-face {\n  font-family: '${family}';\n  src: url('${url}') format('woff2');\n  font-weight: ${WEIGHTS.min} ${WEIGHTS.max};\n  font-style: normal;\n  font-display: swap;\n}\n`;
fs.writeFileSync(
  path.join(ROOT, 'styles/fonts.generated.css'),
  `/* Generated by scripts/subset-fonts.mjs. Do not edit. */\n${face('Noto SC First', out.first.url)}${face('Noto SC', out.rest.url)}`,
);
fs.writeFileSync(
  path.join(ROOT, 'lib/fonts.generated.ts'),
  `// Generated by scripts/subset-fonts.mjs. Do not edit.\nexport const NOTO_FIRST_URL = '${out.first.url}';\n`,
);
console.log('[subset-fonts]', JSON.stringify(out));
